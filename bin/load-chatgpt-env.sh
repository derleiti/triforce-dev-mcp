#!/bin/bash
set -euo pipefail

BASE_DIR="${BASE_DIR:-/home/zombie/workspace/triforce}"
ENV_FILE="${BASE_DIR}/.env"

if [ ! -f "$ENV_FILE" ]; then
    exit 0
fi

while IFS='=' read -r raw_key raw_value; do
    key="$(printf '%s' "$raw_key" | tr -d '[:space:]')"
    case "$key" in
        CHATGPT_URL|CHATGPT_USER|CHATGPT_PASS|GOOGLE_URL|GOOGLE_USER|GOOGLE_PASS|GEMINI_AGENT_ID|GOOGLE_AI_STUDIO_KEY|GEMINI_API_KEY|CLAUDE_URL|CLAUDE_USER|CLAUDE_PASS|CLAUDE_AGENT_ID|NOVA_CHATGPT_URL|NOVA_CHATGPT_USER|NOVA_CHATGPT_PASS|NOVA_CHATGPT_AGENT_ID|NOVA_GOOGLE_URL|NOVA_GOOGLE_USER|NOVA_GOOGLE_PASS|NOVA_GEMINI_AGENT_ID|NOVA_CLAUDE_URL|NOVA_CLAUDE_USER|NOVA_CLAUDE_PASS|NOVA_CLAUDE_AGENT_ID|NOVA_MISTRAL_URL|NOVA_MISTRAL_USER|NOVA_MISTRAL_PASS|NOVA_MISTRAL_AGENT_ID)
            value="${raw_value%$'\r'}"
            value="${value#\"}"
            value="${value%\"}"
            value="${value#\'}"
            value="${value%\'}"
            export "${key}=${value}"
            ;;
    esac
done < <(grep -E '^(CHATGPT_URL|CHATGPT_USER|CHATGPT_PASS|GOOGLE_URL|GOOGLE_USER|GOOGLE_PASS|GEMINI_AGENT_ID|GOOGLE_AI_STUDIO_KEY|GEMINI_API_KEY|CLAUDE_URL|CLAUDE_USER|CLAUDE_PASS|CLAUDE_AGENT_ID|NOVA_CHATGPT_URL|NOVA_CHATGPT_USER|NOVA_CHATGPT_PASS|NOVA_CHATGPT_AGENT_ID|NOVA_GOOGLE_URL|NOVA_GOOGLE_USER|NOVA_GOOGLE_PASS|NOVA_GEMINI_AGENT_ID|NOVA_CLAUDE_URL|NOVA_CLAUDE_USER|NOVA_CLAUDE_PASS|NOVA_CLAUDE_AGENT_ID|NOVA_MISTRAL_URL|NOVA_MISTRAL_USER|NOVA_MISTRAL_PASS|NOVA_MISTRAL_AGENT_ID)=' "$ENV_FILE" || true)
